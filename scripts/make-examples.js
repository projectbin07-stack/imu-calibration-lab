// Regenerates the synthetic example logs in examples/. Every file is
// simulated by src/core/synth.js with a fixed seed; none is sensor data.
// Usage: node scripts/make-examples.js

import { writeFileSync } from "node:fs";
import { VERSION } from "../src/core/export.js";
import { datasetToCsv, synthAccel, synthGyro, synthMag } from "../src/core/synth.js";

const dir = new URL("../examples/", import.meta.url);

/**
 * @param {string} name
 * @param {string} what
 * @param {string} csv
 */
function write(name, what, csv) {
  const head = `# SYNTHETIC ${what}; generated by imu-calibration-lab ${VERSION} scripts/make-examples.js, not sensor data\n`;
  writeFileSync(new URL(name, dir), head + csv);
  console.log(`wrote examples/${name}`);
}

write(
  "accel-15pose.csv",
  "multi-position accelerometer log, 15 poses, 100 Hz, seed 1",
  datasetToCsv(synthAccel({ seed: 1 }).data),
);
write(
  "accel-6pose-mpu6050-raw.csv",
  "six-position log as MPU6050 raw counts (+/-2 g, +/-250 deg/s, t in ms), seed 1",
  datasetToCsv(synthAccel({ seed: 1, poses: "axis" }).data, { raw: true }),
);
write(
  "gyro-turns-mpu6050-raw.csv",
  "gyroscope log with warm-up and 360 deg turns about z, x, -y as MPU6050 raw counts, seed 2",
  datasetToCsv(synthGyro({ seed: 2, holdSeconds: 20 }).data, { raw: true }),
);
write(
  "mag-tumble.csv",
  "magnetometer + accelerometer tumble with hard and soft iron, 50 Hz, seed 3",
  datasetToCsv(synthMag({ seed: 3 }).data, { digits: 5 }),
);
